class VideoItem {
  final int id;
  final String title;
  final String channel;
  final String views;
  final String thumbnailUrl;
  final String duration;
  final String date;

  VideoItem({
    required this.id,
    required this.title,
    required this.channel,
    required this.views,
    required this.thumbnailUrl,
    required this.duration,
    required this.date,
  });
}
